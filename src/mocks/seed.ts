// Anchor dates relative to current runtime so "today", "tomorrow", and "rolling 7 days" always work cleanly
const now = new Date();
const isoOffsetHours = (hoursOffset: number): string => {
  const d = new Date(now.getTime() + hoursOffset * 3600 * 1000);
  d.setMinutes(0, 0, 0);
  return d.toISOString();
};

